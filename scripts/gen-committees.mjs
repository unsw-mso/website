/**
 * Generates lib/data/committees/index.ts from the tenure files in that
 * folder, so adding e.g. 2026-27.ts is all it takes for a new year to show
 * up in the committee page's sidebar. Runs automatically before
 * `npm run dev` and `npm run build` (see package.json).
 */
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'data', 'committees')
const FILE = /^(\d{4})-(\d{2})\.ts$/

const ids = readdirSync(dir)
  .filter((f) => FILE.test(f))
  .map((f) => f.replace(/\.ts$/, ''))
  .sort()
  .reverse() // newest first → shown by default

const skipped = readdirSync(dir).filter((f) => f !== 'index.ts' && !FILE.test(f))
for (const f of skipped) {
  console.warn(`[gen-committees] ignoring ${f}: name tenure files like 2026-27.ts`)
}

// '2025-26' → '25/26'
const label = (id) => `${id.slice(2, 4)}/${id.slice(5, 7)}`
const ident = (id) => `t${id.replace('-', '_')}`

const out = `// AUTO-GENERATED by scripts/gen-committees.mjs — do not edit.
// Add a tenure by creating lib/data/committees/<YYYY>-<YY>.ts instead.
import type { CommitteeMember } from '@/lib/data/committee'
${ids.map((id) => `import { members as ${ident(id)} } from './${id}'`).join('\n')}

export interface Tenure {
  id: string
  label: string
  members: CommitteeMember[]
}

/** Newest first. */
export const tenures: Tenure[] = [
${ids.map((id) => `  { id: '${id}', label: '${label(id)}', members: ${ident(id)} },`).join('\n')}
]
`

writeFileSync(join(dir, 'index.ts'), out)
console.log(`[gen-committees] ${ids.length} tenure(s): ${ids.map(label).join(', ')}`)
